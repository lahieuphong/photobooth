import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const collections = JSON.parse(await readFile(join(root, 'scripts/demo-collections.json'), 'utf8'))
const widths = [160, 320]
const photos = {}
let bytes = 0

// Derive small, uncropped copies from the published masters; never rewrite a master.
for (const collection of collections) {
  const directory = join(root, 'public/images/demo/responsive', collection.id)
  await mkdir(directory, { recursive: true })
  for (let index = 0; index < collection.corners.length; index += 1) {
    const name = String(index + 1).padStart(2, '0')
    const source = join(root, 'public/images/demo', collection.id, `${name}.webp`)
    const metadata = await sharp(source).metadata()
    photos[`${collection.id}/${name}`] = metadata.width
    for (const width of widths.filter((width) => width < metadata.width)) {
      const output = await sharp(source).resize({ width }).webp({ quality: 88, effort: 6 }).toBuffer()
      await writeFile(join(directory, `${name}-${width}.webp`), output)
      bytes += output.length
    }
  }
}

await writeFile(join(root, 'src/features/photobooth/config/demoImageVariants.ts'), `// Generated by yarn demo:variants from the published WebP masters.\nexport const DEMO_IMAGE_VARIANTS = ${JSON.stringify({ widths, photos }, null, 2)} as const\n`)
console.log(`Generated responsive variants for ${Object.keys(photos).length} demo photos (${bytes} bytes).`)

// The 635 px master also remains available for large/high-density brand marks.
for (const width of widths) {
  await sharp(join(root, 'public/images/logos/photobooth-logo.png'))
    .resize({ width }).webp({ lossless: true, effort: 6 })
    .toFile(join(root, `public/images/logos/photobooth-logo-${width}.webp`))
}
